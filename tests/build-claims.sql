-- Runs inside the real M2.1 scenario, after actual baseline and source receipts.
savepoint build_claim_scenario;
grant execute on function civicpulse_delivery.claim_build(text,text),civicpulse_delivery.heartbeat_build(uuid,uuid,bigint) to cp_m21_runner;
create trigger reject_claim before insert on civicpulse_delivery.build_jobs for each row execute function pg_temp.reject_audit();
set session authorization cp_m21_runner;
select pg_temp.denied($q$select civicpulse_delivery.claim_build('9007199254740993:1',repeat('f',40))$q$,'23514');
reset session authorization;
drop trigger reject_claim on civicpulse_delivery.build_jobs;
select pg_temp.assert((select fence=0 from civicpulse_delivery.build_counter) and (select consumed_at is null from civicpulse_delivery.observations where observation_id=(pg_temp.ctx('source_receipt')->>'observation_id')::uuid),'failed claim rolls back fence and receipt');
set session authorization cp_m21_reconciler;
select pg_temp.denied($q$select civicpulse_delivery.claim_build('9007199254740993:1',repeat('f',40))$q$);
reset session authorization;
set session authorization cp_m21_runner;
select pg_temp.denied($q$select civicpulse_delivery.claim_build('9007199254740994:1',repeat('f',40))$q$,'55000');
insert into m21_context values('claim',civicpulse_delivery.claim_build('9007199254740993:1',repeat('f',40)));
select pg_temp.assert(civicpulse_delivery.claim_build('9007199254740993:1',repeat('f',40))=pg_temp.ctx('claim'),'exact active claim replay retains lease');
select pg_temp.denied($q$select civicpulse_delivery.claim_build('9007199254740993:2',repeat('f',40))$q$,'40001');
select pg_temp.denied($q$select civicpulse_delivery.heartbeat_build((pg_temp.ctx('claim')->>'job_id')::uuid,(pg_temp.ctx('claim')->>'lease_id')::uuid,2)$q$,'40001');
select pg_temp.assert(civicpulse_delivery.heartbeat_build((pg_temp.ctx('claim')->>'job_id')::uuid,(pg_temp.ctx('claim')->>'lease_id')::uuid,(pg_temp.ctx('claim')->>'fence')::bigint)->>'lease_expires_at'>=pg_temp.ctx('claim')->>'lease_expires_at','owner heartbeat extends lease');
select pg_temp.denied('select * from civicpulse_delivery.build_jobs');
reset session authorization;
select pg_temp.assert((select count(*)=1 from civicpulse_delivery.build_jobs),'one pinned build job');
select pg_temp.assert((select consumed_for=(pg_temp.ctx('claim')->>'job_id')::uuid from civicpulse_delivery.observations where observation_id=(pg_temp.ctx('source_receipt')->>'observation_id')::uuid),'claim consumes exact actual receipt');
select pg_temp.assert((select fence=1 from civicpulse_delivery.build_counter),'first monotonic fence');
savepoint revoked_runner;
update civicpulse_delivery.machine_registry set enabled=false where role_name='cp_m21_runner';
set session authorization cp_m21_runner;
select pg_temp.denied($q$select civicpulse_delivery.claim_build('9007199254740993:1',repeat('f',40))$q$);
select pg_temp.denied($q$select civicpulse_delivery.heartbeat_build((pg_temp.ctx('claim')->>'job_id')::uuid,(pg_temp.ctx('claim')->>'lease_id')::uuid,(pg_temp.ctx('claim')->>'fence')::bigint)$q$);
reset session authorization;
rollback to revoked_runner;
savepoint desired_change;
set session authorization authenticated;
select public.save_draft('organization','m21-org','{"id":"m21-org","name":"Changed after claim"}',1);
select public.publish('organization','m21-org',2);
reset session authorization;
set session authorization cp_m21_runner;
select pg_temp.denied($q$select civicpulse_delivery.claim_build('9007199254740993:1',repeat('f',40))$q$,'40001');
reset session authorization;
select pg_temp.assert((select target_generation=1 from civicpulse_delivery.build_jobs),'new desired never retargets old claim');
rollback to desired_change;
update civicpulse_delivery.build_jobs set lease_expires_at=clock_timestamp()-interval '1 second';
set session authorization cp_m21_runner;
select pg_temp.denied($q$select civicpulse_delivery.claim_build('9007199254740993:1',repeat('f',40))$q$,'40001');
select pg_temp.denied($q$select civicpulse_delivery.heartbeat_build((pg_temp.ctx('claim')->>'job_id')::uuid,(pg_temp.ctx('claim')->>'lease_id')::uuid,(pg_temp.ctx('claim')->>'fence')::bigint)$q$,'40001');
reset session authorization;
set session authorization cp_m21_operator;
select civicpulse_delivery.set_pipeline_paused(true,'active build cannot be reset');
select pg_temp.denied($q$select civicpulse_delivery.reset_epoch((pg_temp.ctx('claim')->>'dataset_epoch')::uuid,'00000000-0000-4000-8000-000000000099','no expiry takeover')$q$,'55000');
reset session authorization;
rollback to build_claim_scenario;
select pg_temp.assert(not exists(select 1 from civicpulse_delivery.build_jobs) and (select consumed_at is null from civicpulse_delivery.observations where observation_id=(pg_temp.ctx('source_receipt')->>'observation_id')::uuid),'rollback retains unused receipt and no job');
select 'Connected real-receipt claim and heartbeat checks passed' as result;
